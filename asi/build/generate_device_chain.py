"""Generate gpu/src/rr_device_chain_sizes.hpp from asi/third_party/vulkan/include/vulkan/vulkan_core.h."""
from __future__ import annotations

import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
VK_CORE = os.path.join(ROOT, "asi", "third_party", "vulkan", "include", "vulkan", "vulkan_core.h")
OUT_HPP = os.path.join(ROOT, "gpu", "src", "rr_device_chain_sizes.hpp")


def camel_to_vk_stype(struct_name: str) -> str:
    body = struct_name[2:] if struct_name.startswith("Vk") else struct_name
    # Handle Vulkan11Features -> VULKAN_1_1_FEATURES, etc.
    body = re.sub(r"Vulkan([1-9])([0-9])", r"Vulkan_\1_\2_", body)
    # Split transitions like 16Bit -> 16_BIT, 2D -> 2_D? No: Storage16Bit -> STORAGE_16BIT, 16Bit -> 16_BIT
    s1 = re.sub(r"([a-z])([A-Z])", r"\1_\2", body)
    s2 = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", s1)
    s3 = re.sub(r"([a-zA-Z])([0-9])", r"\1_\2", s2)
    s4 = re.sub(r"([0-9])([A-Z])", r"\1_\2", s3)
    tok = "VK_STRUCTURE_TYPE_" + re.sub(r"_+", "_", s4).strip("_").upper()
    return tok


def parse_stypes(text: str) -> dict[str, int]:
    m = re.search(r"typedef enum VkStructureType \{(.*?)\} VkStructureType;", text, re.S)
    if not m:
        raise RuntimeError("VkStructureType enum not found")
    values: dict[str, int] = {}
    for raw in m.group(1).splitlines():
        line = raw.strip().rstrip(",")
        if not line or line.startswith("//") or line.startswith("#"):
            continue
        if "=" not in line:
            continue
        k, v = [x.strip() for x in line.split("=", 1)]
        if "//" in v:
            v = v.split("//", 1)[0].strip().rstrip(",")
        if v.startswith("0x"):
            values[k] = int(v, 16)
        elif v.lstrip("-").isdigit():
            values[k] = int(v)
        elif v in values:
            values[k] = values[v]
    return values


def strip_beta_and_comments(text: str) -> str:
    in_beta = 0
    kept = []
    for ln in text.splitlines(keepends=True):
        if re.match(r"\s*#ifdef\s+VK_ENABLE_BETA_EXTENSIONS\b", ln):
            in_beta += 1
        elif in_beta and re.match(r"\s*#if\b", ln):
            in_beta += 1
        elif in_beta and re.match(r"\s*#endif\b", ln):
            in_beta -= 1
        elif not in_beta:
            kept.append(ln)
    return "".join(kept)


def generate() -> str:
    with open(VK_CORE, "r", encoding="utf-8") as f:
        raw = f.read()
    stype_vals = parse_stypes(raw)
    txt = strip_beta_and_comments(raw)

    # Known non-trivial name mappings between Vk struct name and VK_STRUCTURE_TYPE_*
    # (digit splits like 16Bit / 8Bit / 2 / BPTC / ASTC / S3TC / RGBA / H264).
    compact_map: dict[str, tuple[str, int]] = {}
    for tok, val in stype_vals.items():
        short = tok[len("VK_STRUCTURE_TYPE_"):].replace("_", "")
        compact_map.setdefault(short, (tok, val))

    # Extract all non-video, non-platform structs with { VkStructureType sType; [const] void* pNext; }
    pat = re.compile(
        r"typedef struct (Vk[A-Za-z0-9_]+)\s*\{\s*VkStructureType\s+sType;\s*(?:const\s+)?void\*\s+pNext;",
        re.M,
    )
    structs = pat.findall(txt)
    aliases = dict(re.findall(r"typedef\s+(Vk[A-Za-z0-9_]+)\s+(Vk[A-Za-z0-9_]+)\s*;", txt))

    selected: list[tuple[str, str, int]] = []
    seen_vals: set[int] = set()

    def try_add(struct_name: str, tok_hint: str | None = None) -> None:
        if "Video" in struct_name:
            return
        if not ("Features" in struct_name or struct_name.startswith("VkDevice")):
            return
        tok = tok_hint
        val = stype_vals.get(tok) if tok else None
        if val is None:
            guess = camel_to_vk_stype(struct_name)
            if guess in stype_vals:
                tok, val = guess, stype_vals[guess]
            else:
                compact = struct_name[2:].upper()
                hit = compact_map.get(compact)
                if hit:
                    tok, val = hit
        if tok is None or val is None:
            return
        if val in seen_vals:
            return
        seen_vals.add(val)
        selected.append((tok, struct_name, val))

    for s in structs:
        try_add(s)
    for alias, orig in aliases.items():
        if orig in structs:
            try_add(alias)

    selected.sort(key=lambda item: item[2])
    lines = [
        "// SPDX-License-Identifier: MIT",
        "// Generated by asi/build/generate_device_chain.py from vulkan_core.h.",
        "#pragma once",
        "#include <vulkan/vulkan.h>",
        "#include <cstddef>",
        "",
        "namespace onr_host {",
        "",
        "inline size_t pnext_struct_size(VkStructureType sType) {",
        "    switch (sType) {",
    ]
    for tok, sname, _ in selected:
        lines.append(f"    case {tok}: return sizeof({sname});")
    lines.extend([
        "    default: return 0;",
        "    }",
        "}",
        "",
        "}  // namespace onr_host",
        "",
    ])
    return "\n".join(lines)


def main() -> int:
    code = generate()
    os.makedirs(os.path.dirname(OUT_HPP), exist_ok=True)
    with open(OUT_HPP, "w", encoding="utf-8", newline="\n") as f:
        f.write(code)
    print(f"Wrote {OUT_HPP} ({code.count('case ')} sType entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
