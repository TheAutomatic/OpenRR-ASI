#!/usr/bin/env bash
# SPDX-License-Identifier: MIT
# The Vulkan entry points of a DLL of ours, resolved at run time instead of imported: a static import of vulkan-1.dll
# loads the Vulkan loader into every game before its own graphics stack. Every vk* call goes through a pointer filled
# by rr_vk_load() from vulkan-1.dll (one tail jump per entry point).
#
#   vulkan_lazy.sh <out dir> <link command...>
# The link command (without -o) is run once: the undefined vk* names it reports are the entry points. Writes
# <out dir>/vulkan_lazy_s.o and vulkan_lazy_c.o.
set -euo pipefail
out=$1; shift
cc=${RR_MINGW_CC:-x86_64-w64-mingw32-gcc}
undefined=$({ "$@" -o /dev/null 2>&1 || true; } |
    grep -o "undefined reference to \`_*vk[A-Za-z0-9_@]*'" | sed "s/.*\`//; s/'//" | sort -u)
{
    echo '// Generated by asi/build/vulkan_lazy.sh. One tail jump per entry point.'
    echo '    .text'
    for sym in $undefined; do printf '    .globl %s\n%s:\n    jmp *rr_vk_p_%s(%%rip)\n' "$sym" "$sym" "$sym"; done
    echo '    .data'
    for sym in $undefined; do printf '    .globl rr_vk_p_%s\n    .align 8\nrr_vk_p_%s:\n    .quad rr_vk_unresolved\n' "$sym" "$sym"; done
} > "$out/vulkan_lazy.s"
{
    echo '// Generated by asi/build/vulkan_lazy.sh.'
    echo '#include <windows.h>'
    echo 'long rr_vk_unresolved(void) { return -3; }   // VK_ERROR_INITIALIZATION_FAILED'
    for sym in $undefined; do printf 'extern void* rr_vk_p_%s;\n' "$sym"; done
    printf 'static const char* const rr_vk_names[] = {'
    for sym in $undefined; do printf '"%s", ' "$sym"; done
    echo '};'
    printf 'static void** const rr_vk_slots[] = {'
    for sym in $undefined; do printf '&rr_vk_p_%s, ' "$sym"; done
    echo '};'
    # device-level commands (their first parameter a VkDevice, VkQueue or VkCommandBuffer): the rest take the
    # loader's instance / physical-device objects and stay the loader's in rr_vk_device_direct
    instance_level='^vk(CreateInstance|DestroyInstance|EnumerateInstance.*|EnumeratePhysicalDevice.*|GetPhysicalDevice.*|CreateDevice|EnumerateDevice.*|GetInstanceProcAddr|GetDeviceProcAddr|Create.*SurfaceKHR|DestroySurfaceKHR|.*DebugUtils.*|.*DebugReport.*)$'
    printf 'static const unsigned char rr_vk_device_level[] = {'
    for sym in $undefined; do
        if [[ "$sym" =~ $instance_level ]]; then printf '0, '; else printf '1, '; fi
    done
    echo '};'
    cat <<'C'
#define RR_VK_COUNT (sizeof rr_vk_names / sizeof rr_vk_names[0])
static HMODULE rr_vk_from;
const char* rr_vk_source = "none";      /* the DLL the entry points came from, for the log */
int rr_vk_missing;                       /* entry points that DLL does not export (they return an error, or do nothing) */
const char* rr_vk_first_missing = "";
/* Safe to call again: it changes nothing once vulkan-1.dll's entry points are in. */
void rr_vk_load(void) {
    HMODULE m = GetModuleHandleW(L"vulkan-1.dll");
    if (!m) m = LoadLibraryW(L"vulkan-1.dll");
    if (!m || m == rr_vk_from) return;
    rr_vk_from = m;
    rr_vk_source = "vulkan-1.dll";
    rr_vk_missing = 0;
    rr_vk_first_missing = "";
    for (unsigned i = 0; i < RR_VK_COUNT; ++i) {
        void* p = (void*)GetProcAddress(m, rr_vk_names[i]);
        if (!p) {
            p = (void*)rr_vk_unresolved;
            if (!rr_vk_missing++) rr_vk_first_missing = rr_vk_names[i];
        }
        *rr_vk_slots[i] = p;
    }
}
/* The Linux version's choice between Wine's driver and the loader; on Windows there is only the loader. */
void rr_vk_use_loader(int yes) { (void)yes; }
/* ReShade's Vulkan layer drops a device from its table before it tells the add-ons the device is going (its
   vkDestroyDevice): a call of ours through the loader then lands in ReShade's hooks of that device and crashes there.
   While the add-on frees OpenRR's objects of that device, its device-level entry points are the driver's own: AMD's
   Vulkan driver (amdvlk64.dll, the loader's ICD; the loader hands the application the driver's own VkDevice).
   rr_vk_device_direct(0, 0) puts the loader's back. 1: switched, -1: the driver's functions were not found (OpenRR's
   objects of that device are then left to the device's end). */
#include <tlhelp32.h>
#include <wchar.h>
typedef void* (__stdcall *rr_gpa_t)(void*, const char*);   /* PFN_vkGet{Instance,Device}ProcAddr (VKAPI_CALL = __stdcall) */
static void* rr_vk_saved[RR_VK_COUNT];
static int rr_vk_direct_on;
int rr_vk_device_direct(void* device, int on) {
    if (!on) {
        if (rr_vk_direct_on)
            for (unsigned i = 0; i < RR_VK_COUNT; ++i) *rr_vk_slots[i] = rr_vk_saved[i];
        rr_vk_direct_on = 0;
        return 1;
    }
    if (rr_vk_direct_on) return 1;
    if (!device) return -1;
    HMODULE driver = 0;
    HANDLE snap = CreateToolhelp32Snapshot(TH32CS_SNAPMODULE, 0);
    if (snap == INVALID_HANDLE_VALUE) return -1;
    MODULEENTRY32W me; me.dwSize = sizeof me;
    for (BOOL more = Module32FirstW(snap, &me); more && !driver; more = Module32NextW(snap, &me))
        if (!_wcsnicmp(me.szModule, L"amdvlk", 6) && GetProcAddress(me.hModule, "vk_icdGetInstanceProcAddr"))
            driver = me.hModule;
    CloseHandle(snap);
    if (!driver) return -1;
    rr_gpa_t gdpa = (rr_gpa_t)(void*)GetProcAddress(driver, "vkGetDeviceProcAddr");
    if (!gdpa) {
        rr_gpa_t icd = (rr_gpa_t)(void*)GetProcAddress(driver, "vk_icdGetInstanceProcAddr");
        gdpa = icd ? (rr_gpa_t)icd(0, "vkGetDeviceProcAddr") : 0;
    }
    if (!gdpa || !gdpa(device, "vkDestroyImage")) return -1;
    for (unsigned i = 0; i < RR_VK_COUNT; ++i) {
        rr_vk_saved[i] = *rr_vk_slots[i];
        void* p = rr_vk_device_level[i] ? gdpa(device, rr_vk_names[i]) : 0;
        if (p) *rr_vk_slots[i] = p;
    }
    rr_vk_direct_on = 1;
    return 1;
}
C
} > "$out/vulkan_lazy.c"
"$cc" -c "$out/vulkan_lazy.s" -o "$out/vulkan_lazy_s.o"
"$cc" -O2 -c "$out/vulkan_lazy.c" -o "$out/vulkan_lazy_c.o"
echo "Vulkan entry points resolved at run time: $(echo "$undefined" | grep -c . || true)"
